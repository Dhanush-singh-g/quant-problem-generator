import { expect, test } from "@playwright/test";

test("candidate registration, saved progress, review, revision, profile and logout", async ({ page }) => {
  const failures: string[] = [];
  page.on("pageerror", e => failures.push(e.message));
  await page.goto("/register");
  await page.getByLabel("Name", { exact: true }).fill("Browser Candidate");
  await page.getByLabel("Email", { exact: true }).fill(`candidate-${Date.now()}@example.com`);
  await page.getByLabel("Password", { exact: true }).fill("Browser-test-password-123");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Build your practice set" })).toBeVisible();
  await expect(page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Profile", exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "Topic", exact: true }).selectOption("Time, Speed & Distance");
  await page.getByLabel("Set size").fill("5");
  await page.getByRole("button", { name: "Start practice", exact: true }).click();
  const options = page.locator('button[aria-pressed]');
  await expect(options).toHaveCount(4);
  await options.first().click();
  await page.getByRole("button", { name: "Next", exact: true }).click();
  await page.getByRole("button", { name: "Save now / retry", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: /^Saved$/ })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Question 2 of 5", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Go to question 1", exact: true }).click();
  await expect(page.locator('button[aria-pressed="true"]')).toHaveCount(1);
  await page.getByRole("button", { name: "Save for revision", exact: true }).click();
  await page.getByRole("button", { name: "Finish set", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Practice complete/ })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: /Practice complete/ })).toBeVisible();
  await page.getByRole("navigation").getByRole("link", { name: "Profile", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Browser Candidate practice stats" })).toBeVisible();
  await expect(page.getByText("Questions completed", { exact: true })).toBeVisible();
  await page.getByRole("navigation").getByRole("link", { name: "Saved", exact: true }).click();
  await expect(page.getByText(/Correct option:/)).toBeVisible();
  await page.getByRole("button", { name: "Remove", exact: true }).click();
  await expect(page.getByText("No saved questions yet.")).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("navigation").getByRole("link", { name: "Practice", exact: true })).toBeVisible();
  await page.getByRole("navigation").getByRole("link", { name: "Practice", exact: true }).click();
  await page.getByRole("combobox", { name: "Mode", exact: true }).selectOption("revision");
  await page.getByLabel("Set size").fill("1");
  await page.getByRole("button", { name: "Start practice", exact: true }).click();
  await expect(page.locator('button[aria-pressed]')).toHaveCount(4);
  await page.getByRole("button", { name: "Discard this set", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Build your practice set" })).toBeVisible();
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await expect(page.getByRole("banner").getByRole("link", { name: "Sign in", exact: true })).toBeVisible();
  await page.goto("/admin");
  await expect(page.getByRole("heading", { name: "Sign in to continue" })).toBeVisible();
  expect(failures).toEqual([]);
});

test("administrator generates a complete batch, creates an assessment and candidate resumes it", async ({ page, browser, baseURL }) => {
  test.skip(!process.env.E2E_ADMIN_PASSWORD, "Set disposable administrator credentials for the admin browser test");
  await page.goto("/login");
  await page.getByLabel("Email", { exact: true }).fill(process.env.E2E_ADMIN_EMAIL || "admin@example.com");
  await page.getByLabel("Password", { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD!);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("navigation").getByRole("link", { name: "Factory", exact: true })).toBeVisible();
  await page.getByRole("navigation").getByRole("link", { name: "Factory", exact: true }).click();
  await page.getByRole("combobox", { name: "Topic", exact: true }).selectOption("Time, Speed & Distance");
  await page.getByRole("combobox", { name: "Difficulty", exact: true }).selectOption("hard");
  await page.getByLabel("Questions", { exact: true }).fill("12");
  await page.getByRole("button", { name: "Generate batch", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Saved all 12");
  await expect(page.getByText("12/12", { exact: true })).toBeVisible({ timeout: 45000 });
  await page.getByRole("navigation").getByRole("link", { name: "Manage exams", exact: true }).click();
  const title = `Browser assessment ${Date.now()}`;
  await page.getByLabel("Title", { exact: true }).fill(title);
  await page.getByLabel("Easy questions", { exact: true }).fill("1");
  await page.getByLabel("Medium questions", { exact: true }).fill("1");
  await page.getByLabel("Expected candidates", { exact: true }).fill("10");
  await page.getByLabel("Candidates per variant", { exact: true }).fill("5");
  await page.getByLabel("Time, Speed & Distance", { exact: true }).check();
  await page.getByRole("button", { name: "Preview distribution", exact: true }).click();
  await expect(page.getByText("2 questions · 2 reusable variants", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Create draft", exact: true }).click();
  const card = page.locator("article").filter({ has: page.getByRole("heading", { name: title, exact: true }) });
  await card.getByRole("button", { name: "Activate", exact: true }).click();
  await expect(card).toContainText("active");
  const context = await browser.newContext({ baseURL });
  const candidate = await context.newPage();
  await candidate.goto("/register");
  await candidate.getByLabel("Name", { exact: true }).fill("Exam Candidate");
  await candidate.getByLabel("Email", { exact: true }).fill(`exam-${Date.now()}@example.com`);
  await candidate.getByLabel("Password", { exact: true }).fill("Browser-test-password-123");
  await candidate.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(candidate.getByRole("heading", { name: "Build your practice set" })).toBeVisible();
  await candidate.getByRole("navigation").getByRole("link", { name: "Assessments", exact: true }).click();
  await candidate.getByRole("button", { name: "Start assessment", exact: true }).click();
  await expect(candidate.locator('button[aria-pressed]')).toHaveCount(4);
  await candidate.locator('button[aria-pressed]').first().click();
  await expect(candidate.getByRole("status").filter({ hasText: /^Saved$/ })).toBeVisible();
  await candidate.reload();
  await candidate.getByRole("button", { name: "Resume assessment", exact: true }).click();
  await expect(candidate.locator('button[aria-pressed="true"]')).toHaveCount(1);
  await candidate.getByRole("button", { name: "Submit assessment", exact: true }).click();
  await expect(candidate.getByRole("heading", { name: "Assessment submitted" })).toBeVisible();
  await card.getByRole("button", { name: "Close to new candidates", exact: true }).click();
  await candidate.reload();
  await candidate.getByRole("button", { name: "View review", exact: true }).click();
  await expect(candidate.getByText(/Score:/)).toBeVisible();
  await card.getByRole("button", { name: "Leaderboard", exact: true }).click();
  await expect(page.getByText(/Exam Candidate:/)).toBeVisible();
  await context.close();
});
